// Frozen schema-2 catalog contract. Catalog changes require a new migration/revision.
import { products } from '../src/domain/catalog.ts';
import { writeFileSync } from 'node:fs';
const object = (properties, required = Object.keys(properties)) => ({
  type: 'object',
  properties,
  required,
  additionalProperties: false,
});
const text = (max = 80) => ({ type: 'string', minLength: 1, maxLength: max });
const dimension = (
  min = Number.MIN_VALUE,
  max = 100,
  source = ['sample', 'user_entered'],
) =>
  object(
    {
      meters: { type: 'number', minimum: min, maximum: max },
      source: { enum: source },
      uncertaintyMeters: { type: 'number', minimum: 0 },
      evidence: object({
        reference: text(500),
        recordedAt: text(),
      }),
    },
    ['meters', 'source'],
  );
const dimensions = (w, d, h) => object({ width: w, depth: d, height: h });
const placement = products.map((p) =>
  object({
    id: { ...text(), pattern: '^[\\w-]{1,80}$' },
    roomId: text(),
    productId: { const: p.id },
    productRevision: { const: p.revision },
    assetRevisionId: { const: p.assetRevisionId },
    materialVariantId: { enum: p.variants.map((v) => v.id) },
    dimensions: dimensions(
      ...['width', 'depth', 'height'].map((a) => {
        const range = p.adjustable[a];
        return range
          ? dimension(range.min, range.max)
          : {
              ...dimension(),
              properties: {
                ...dimension().properties,
                meters: { const: p.dimensions[a].meters },
                source: { const: 'sample' },
              },
            };
      }),
    ),
    position: object({
      x: { type: 'number', minimum: -100, maximum: 100 },
      y: { const: 0 },
      z: { type: 'number', minimum: -100, maximum: 100 },
    }),
    rotationYRadians: {
      type: 'number',
      minimum: -Math.PI - 0.000001,
      maximum: Math.PI + 0.000001,
    },
  }),
);
const schema = object({
  schemaVersion: { const: 2 },
  displayUnits: { enum: ['metric', 'imperial'] },
  room: object({
    id: text(),
    name: text(120),
    dimensions: dimensions(
      dimension(1, 30),
      dimension(1, 30),
      dimension(1.8, 6),
    ),
    openings: { type: 'array', maxItems: 0 },
    wallMaterialId: { enum: ['plaster', 'chalk', 'sage', 'clay', 'charcoal'] },
    floorMaterialId: { enum: ['oak', 'walnut', 'stone', 'concrete'] },
  }),
  placements: { type: 'array', maxItems: 100, items: { oneOf: placement } },
  spatial: object({
    clearanceMeters: { type: 'number', minimum: 0, maximum: 3 },
    doorway: object({
      width: { anyOf: [{ type: 'null' }, dimension(0.2, 5)] },
      height: { anyOf: [{ type: 'null' }, dimension(0.5, 4)] },
    }),
  }),
});
const json = JSON.stringify(schema);
writeFileSync(
  'supabase/scene-schema.json',
  JSON.stringify(schema, null, 2) + '\n',
);
writeFileSync(
  'supabase/migrations/20261114000000_scene_contract.sql',
  `-- Generated by scripts/generate-scene-schema.mjs. Freeze after deployment.\ncreate extension if not exists pg_jsonschema with schema extensions;\ncreate or replace function public.valid_scene(doc jsonb) returns boolean language plpgsql immutable set search_path = '' as $fn$\nbegin\n  if octet_length(doc::text)>1048576 or not extensions.jsonb_matches_schema($schema$${json}$schema$::json, doc) then return false; end if;\n  return not exists(select 1 from jsonb_array_elements(doc->'placements') p where p->>'roomId' <> doc->'room'->>'id')\n    and (select count(*)=count(distinct p->>'id') from jsonb_array_elements(doc->'placements') p);\nexception when others then return false;\nend $fn$;\nrevoke all on function public.valid_scene(jsonb) from public;\n`,
);
